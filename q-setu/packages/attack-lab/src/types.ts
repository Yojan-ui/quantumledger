import type { Action, GuardEvent } from "@qsetu/shield-guard";

/** What kind of client a request came from, read from its user agent. The raw agent is not kept. */
export type ClientFamily =
  "browser" | "headless" | "script" | "ai-agent" | "search-bot" | "none" | "other";

/**
 * One request from a flagged source, as kept on record. Privacy-safe by construction: no bodies, no
 * query strings, no headers beyond the client family, and the IP only as a keyed hash.
 */
export interface AttackEvent {
  /** The protected site (customer) the request was sent to. */
  site: string;
  at: number;
  source: {
    /** HMAC-SHA256 of the IP under the lab's own salt, 16 hex characters. */
    ipHash: string;
    /** The same for the /24 (IPv4) or /48 (IPv6) block. */
    netHash: string;
    asn?: string;
    /** Hash of the Shield pass cookie, when the client had one. */
    sessionHash?: string;
  };
  /** Only when the request came through Shield Edge, which is the only place TLS is visible. */
  tls?: { ja4?: string };
  client: ClientFamily;
  method: string;
  /** Path only, at most 120 characters, canary keys replaced with "[canary]". */
  route: string;
  /** True when Shield's engine raised an event for this request; false for steps around it. */
  flagged: boolean;
  /** The engine's event types for this request (honeypot, block, limit…). */
  types: GuardEvent["type"][];
  /** The engine's reasons, as it wrote them. */
  signals: string[];
  score: number;
  /** What Shield did. "allow" for unflagged steps that went through. */
  action: Action;
  status: number;
  /** Shield was in monitor mode: it would have acted but let the request through. */
  monitorOnly: boolean;
  /** Generated by the lab's own test traffic, not seen in the wild. */
  synthetic: boolean;
}

/** A signed, hash-chained entry in the evidence log. Never changed after it is written. */
export interface SignedRecord<T = unknown> {
  v: 1;
  kind: "event" | "incident";
  seq: number;
  /** The previous record's hash ("" for the first): removing or reordering records breaks the chain. */
  prev: string;
  body: T;
  alg: "ML-DSA-65";
  keyId: string;
  /** SHA-256 of the signed bytes, hex. */
  hash: string;
  /** ML-DSA-65 signature over the same bytes, base64. */
  sig: string;
}

export type EventRecord = SignedRecord<AttackEvent & { id: string; incidentId: string }>;

/** Events that share a source or session, close together in time. */
export interface Incident {
  id: string;
  site: string;
  opened: number;
  lastSeen: number;
  ipHashes: string[];
  sessionHashes: string[];
  asns: string[];
  clients: ClientFamily[];
  eventIds: string[];
  /** Each event record's hash, in order: the incident's signature covers them. */
  eventHashes: string[];
  flagged: number;
  maxScore: number;
  signals: string[];
  types: GuardEvent["type"][];
  synthetic: boolean;
}

export type IncidentRecord = SignedRecord<Incident>;

export type Phase = "recon" | "probe" | "credential" | "abuse" | "blocked" | "browse";

export interface TimelineStep {
  i: number;
  eventId: string;
  at: number;
  /** Milliseconds since the incident's first step. */
  offsetMs: number;
  method: string;
  route: string;
  routeClass: RouteClass;
  phase: Phase;
  flagged: boolean;
  signals: string[];
  types: GuardEvent["type"][];
  score: number;
  action: Action;
  status: number;
  client: ClientFamily;
}

export type RouteClass = "secrets" | "admin" | "api" | "page" | "trap" | "other";

export interface Pattern {
  id: string;
  name: string;
  description: string;
  count: number;
  firstSeen: number;
  lastSeen: number;
  incidentIds: string[];
  topRoutes: { route: string; n: number }[];
  clients: ClientFamily[];
}
