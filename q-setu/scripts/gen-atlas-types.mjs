// Generates apps/web/lib/client/atlas-types.ts from Atlas's JSON contracts (qshield/contracts/*.schema.json).
// Run after a contract changes: pnpm gen:atlas-types. The output is committed and never edited by hand.
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const root = new URL("../../qshield/contracts/", import.meta.url);
const out = new URL("../apps/web/lib/client/atlas-types.ts", import.meta.url);
const schemas = [
  ["results.schema.json", "AtlasResults"],
  ["bench.schema.json", "AtlasBench"],
  ["ledger_entry.schema.json", "AtlasLedgerEntry"],
];
let ts =
  "// GENERATED by scripts/gen-atlas-types.mjs from qshield/contracts/*.schema.json. Do not edit.\n";
// allOf / if / then / else / not are value rules (e.g. "non-ok rows have metrics null"), not shape: the
// generator turns them into opaque intersections, so they are dropped here; the declared properties stay.
const shapeOnly = (n) => {
  if (Array.isArray(n)) return n.map(shapeOnly);
  if (!n || typeof n !== "object") return n;
  return Object.fromEntries(
    Object.entries(n)
      .filter(([k]) => !["allOf", "if", "then", "else", "not"].includes(k))
      .map(([k, v]) => [k, shapeOnly(v)]),
  );
};
for (const [file, name] of schemas) {
  const schema = shapeOnly(JSON.parse(readFileSync(new URL(file, root), "utf8")));
  schema.title = name;
  ts += "\n" + (await compile(schema, name, { bannerComment: "", format: false }));
}
writeFileSync(out, ts);
console.log(`wrote ${out.pathname}`);
