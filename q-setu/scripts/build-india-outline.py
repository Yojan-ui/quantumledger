import json, sys, math
src, out = sys.argv[1], sys.argv[2]
fc = json.load(open(src))
feat = [f for f in fc["features"] if f["properties"].get("ADM0_A3") == "IND" or f["properties"].get("ADM0_A3_IN") == "IND"]
assert len(feat) == 1, [f["properties"].get("NAME") for f in feat]
g = feat[0]["geometry"]
polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]

def area(r):
    return abs(sum(r[i][0]*r[i+1][1]-r[i+1][0]*r[i][1] for i in range(len(r)-1))/2)

def dp(pts, eps):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]
    dx, dy = b[0]-a[0], b[1]-a[1]
    L = math.hypot(dx, dy) or 1e-12
    dmax, idx = 0, 0
    for i in range(1, len(pts)-1):
        d = abs(dy*pts[i][0]-dx*pts[i][1]+b[0]*a[1]-b[1]*a[0])/L
        if d > dmax: dmax, idx = d, i
    if dmax > eps:
        return dp(pts[:idx+1], eps)[:-1] + dp(pts[idx:], eps)
    return [a, b]

rings = []
for p in polys:
    outer = p[0]
    A = area(outer)
    if A < 0.05: continue  # drop specks; keeps the mainland and the larger Andaman & Nicobar islands
    eps = 0.06 if A > 50 else 0.02
    # A closed ring starts and ends at the same point, so split it at the farthest vertex first.
    k = max(range(len(outer)), key=lambda i: math.hypot(outer[i][0]-outer[0][0], outer[i][1]-outer[0][1]))
    s = dp(outer[:k+1], eps)[:-1] + dp(outer[k:], eps)
    rings.append({"area": round(A, 2), "points": [[round(x, 3), round(y, 3)] for x, y in s]})
rings.sort(key=lambda r: -r["area"])
allpts = [pt for r in rings for pt in r["points"]]
bbox = [min(p[0] for p in allpts), min(p[1] for p in allpts), max(p[0] for p in allpts), max(p[1] for p in allpts)]
json.dump({
  "source": "Natural Earth 1:10m Admin 0 Countries, India point of view (ne_10m_admin_0_countries_ind)",
  "sourceUrl": "https://www.naturalearthdata.com/",
  "license": "Public domain",
  "note": "Simplified (Douglas-Peucker). Generated by scripts/build-india-outline.py",
  "bbox": bbox,
  "rings": [r["points"] for r in rings],
}, open(out, "w"), separators=(",", ":"))
print(len(rings), [len(r["points"]) for r in rings], bbox)
