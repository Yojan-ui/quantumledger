"use client";
import Link from "next/link";
import { usePathname } from "next/navigation";
import type { Phase } from "@qsetu/attack-lab";
import { usePoll, type Overview } from "./api";

const LINKS = [
  ["/", "Incidents"],
  ["/patterns", "Patterns"],
  ["/replay", "Replay"],
] as const;

export function Nav() {
  const path = usePathname();
  const { data } = usePoll<Overview>("/api/overview", 10_000);
  return (
    <header className="top">
      <div className="top-in">
        <Link href="/" className="brand">
          Attack Lab <small>QuantumLedger</small>
        </Link>
        <nav className="nav" aria-label="Sections">
          {LINKS.map(([href, label]) => {
            const on =
              href === "/" ? path === "/" || path.startsWith("/incidents") : path.startsWith(href);
            return (
              <Link key={href} href={href} aria-current={on ? "page" : undefined}>
                {label}
              </Link>
            );
          })}
        </nav>
        <span className="key mono" title={data?.key.publicKey}>
          <span className="dot c-sig" />
          {data ? `${data.key.alg} · key ${data.key.keyId}` : "lab API offline"}
        </span>
      </div>
    </header>
  );
}

/** What Shield did, in its role colour: refused = protected (ok), let through = attack reached (warn). */
export function ActionChip({ action, monitor }: { action: string; monitor?: boolean }) {
  const label = monitor
    ? "would act"
    : action === "allow"
      ? "allowed"
      : action === "limit"
        ? "limited"
        : action === "challenge"
          ? "challenged"
          : "blocked";
  const tone = action === "allow" || monitor ? "c-2" : "c-ok";
  return (
    <span className={`chip ${tone}`}>
      <span className="dot" />
      {label}
    </span>
  );
}

export const PHASE: Record<Phase, { label: string; tone: string }> = {
  browse: { label: "browse", tone: "c-3" },
  recon: { label: "recon", tone: "c-2" },
  probe: { label: "probe", tone: "c-warn" },
  credential: { label: "credential", tone: "c-danger" },
  abuse: { label: "abuse", tone: "c-danger" },
  blocked: { label: "refused", tone: "c-ok" },
};

export function PhaseChip({ phase }: { phase: Phase }) {
  const p = PHASE[phase];
  return (
    <span className={`chip ${p.tone}`}>
      <span className="dot" />
      {p.label}
    </span>
  );
}

export function Synthetic({ on }: { on: boolean }) {
  return on ? (
    <span className="chip c-3" title="Generated by the lab's own test traffic">
      test traffic
    </span>
  ) : null;
}

export function Score({ n }: { n: number }) {
  const tone = n >= 80 ? "c-danger" : n >= 30 ? "c-warn" : "c-3";
  return (
    <span className={`row ${tone}`} style={{ gap: 8 }}>
      <span className="bar">
        <span style={{ width: `${n}%` }} />
      </span>
      <span className="mono">{n}</span>
    </span>
  );
}
